const originalNodeTextMap = typeof WeakMap !== "undefined" ? new WeakMap() : null;

export function useGlobalLanguageSync(langCode = "EN") {
  useEffect(() => {
    if (typeof window === "undefined" || typeof document === "undefined") return;
    localStorage.setItem("we4all_selected_lang", langCode);
    const dict = getLangText(langCode);

    const translateDomTree = () => {
      const walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT, null);
      let node;
      while ((node = walker.nextNode())) {
        const raw = node.nodeValue;
        if (!raw || !raw.trim()) continue;
        if (originalNodeTextMap && !originalNodeTextMap.has(node)) {
          originalNodeTextMap.set(node, raw);
        }
        const sourceText = (originalNodeTextMap && originalNodeTextMap.get(node)) || raw;
        if (langCode === "EN") {
          if (node.nodeValue !== sourceText) node.nodeValue = sourceText;
          continue;
        }
        let nextText = sourceText;
        for (const item of COMMON_PHRASES) {
          if (nextText.trim() === item.en && dict[item.key]) {
            nextText = dict[item.key];
            break;
          }
        }
        if (node.nodeValue !== nextText) {
          node.nodeValue = nextText;
        }
      }
    };

    translateDomTree();
    const observer = new MutationObserver(() => {
      translateDomTree();
    });
    observer.observe(document.body, { childList: true, subtree: true });
    return () => observer.disconnect();
  }, [langCode]);
}